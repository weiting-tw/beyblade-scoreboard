// PCF85063 即時時鐘（I2C 0x51）。
//
// 只做歷史紀錄需要的事：讀出時間、判斷這個時間可不可信、必要時設定一次。
// 沒有做鬧鐘、計時器、CLKOUT 那些功能 —— 用不到。
#pragma once

#include <cstdint>

namespace bey {

// 讀出目前時間的 epoch 秒。
//
// 注意：這是**本地時間**的 epoch 表示，不是真正的 UTC epoch。這台是單機
// 計分器，沒有跨時區需求，也沒有網路可以校時 —— 整條鏈路（寫入、讀出、
// 歷史紀錄顯示）都用同一個本地時間就一致了，中間不做任何時區換算。
// 真的要接 NTP 時再改成 UTC，那時顯示端要跟著加時區偏移。
//
// 讀取失敗或振盪器停過（時間不可信）時回傳 0。
uint32_t rtcNowEpoch();

// 開機時呼叫一次。
//
// 振盪器停過代表沒有備援電池、或這顆是第一次上電，暫存器裡是垃圾值。
// 這時用韌體的建置時間當起點 —— 不準（頂多差到上次燒錄的時間），但總比
// 歷史紀錄全部顯示 1970 或亂數日期好。時間對得上不對得上，使用者一看就知道。
void rtcBegin();

// 設定時間。epoch 為本地時間秒，語意同 rtcNowEpoch()。
bool rtcSetEpoch(uint32_t epoch);

}  // namespace bey
