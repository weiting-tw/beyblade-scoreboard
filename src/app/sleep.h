// 自動休眠：閒置一段時間後關背光。
//
// 只關背光，不做深度睡眠 —— 深睡會停掉本局計時、斷開序列埠、喚醒還要重建
// 整個 UI，對一台比賽中的計分器不划算。背光本來就是這塊板子最大的耗電源。
//
// 比賽流程中的畫面（倒數、計分、局結果、完成）永遠不休眠：陀螺在轉的時候
// 沒有人會去摸螢幕，而那正是最需要看得到分數的時刻。這條規則和「收起狀態
// 晶片」「手勢返回不生效」是同一組畫面。
#pragma once

#include <cstdint>

namespace bey {

// 有使用者活動（觸控、按鍵）。休眠中呼叫會立刻喚醒。
void sleepNoteActivity();

// 每輪 loop 呼叫一次。
void sleepPoll();

// 螢幕是否已經熄掉。熄掉時第一次觸控只用來喚醒，不該傳給 UI ——
// 否則摸黑點下去會誤觸到當時畫面上的任何按鈕。
bool sleepScreenOff();

}  // namespace bey
